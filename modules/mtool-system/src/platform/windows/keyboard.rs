use mapp::keyboard_types::Code;

pub(crate) fn scancode_to_physicalkey(scancode: u32) -> Option<Code> {
    // See: https://www.win.tue.nl/~aeb/linux/kbd/scancodes-1.html
    // and: https://www.w3.org/TR/uievents-code/
    // and: The widget/NativeKeyToDOMCodeName.h file in the firefox source

    Some(match scancode {
        0x0029 => Code::Backquote,
        0x002b => Code::Backslash,
        0x000e => Code::Backspace,
        0x001a => Code::BracketLeft,
        0x001b => Code::BracketRight,
        0x0033 => Code::Comma,
        0x000b => Code::Digit0,
        0x0002 => Code::Digit1,
        0x0003 => Code::Digit2,
        0x0004 => Code::Digit3,
        0x0005 => Code::Digit4,
        0x0006 => Code::Digit5,
        0x0007 => Code::Digit6,
        0x0008 => Code::Digit7,
        0x0009 => Code::Digit8,
        0x000a => Code::Digit9,
        0x000d => Code::Equal,
        0x0056 => Code::IntlBackslash,
        0x0073 => Code::IntlRo,
        0x007d => Code::IntlYen,
        0x001e => Code::KeyA,
        0x0030 => Code::KeyB,
        0x002e => Code::KeyC,
        0x0020 => Code::KeyD,
        0x0012 => Code::KeyE,
        0x0021 => Code::KeyF,
        0x0022 => Code::KeyG,
        0x0023 => Code::KeyH,
        0x0017 => Code::KeyI,
        0x0024 => Code::KeyJ,
        0x0025 => Code::KeyK,
        0x0026 => Code::KeyL,
        0x0032 => Code::KeyM,
        0x0031 => Code::KeyN,
        0x0018 => Code::KeyO,
        0x0019 => Code::KeyP,
        0x0010 => Code::KeyQ,
        0x0013 => Code::KeyR,
        0x001f => Code::KeyS,
        0x0014 => Code::KeyT,
        0x0016 => Code::KeyU,
        0x002f => Code::KeyV,
        0x0011 => Code::KeyW,
        0x002d => Code::KeyX,
        0x0015 => Code::KeyY,
        0x002c => Code::KeyZ,
        0x000c => Code::Minus,
        0x0034 => Code::Period,
        0x0028 => Code::Quote,
        0x0027 => Code::Semicolon,
        0x0035 => Code::Slash,
        0x0038 => Code::AltLeft,
        0xe038 => Code::AltRight,
        0x003a => Code::CapsLock,
        0xe05d => Code::ContextMenu,
        0x001d => Code::ControlLeft,
        0xe01d => Code::ControlRight,
        0x001c => Code::Enter,
        0xe05b => Code::Super,
        0xe05c => Code::Super,
        0x002a => Code::ShiftLeft,
        0x0036 => Code::ShiftRight,
        0x0039 => Code::Space,
        0x000f => Code::Tab,
        0x0079 => Code::Convert,
        0x0072 => Code::Lang1, // for non-Korean layout
        0xe0f2 => Code::Lang1, // for Korean layout
        0x0071 => Code::Lang2, // for non-Korean layout
        0xe0f1 => Code::Lang2, // for Korean layout
        0x0070 => Code::KanaMode,
        0x007b => Code::NonConvert,
        0xe053 => Code::Delete,
        0xe04f => Code::End,
        0xe047 => Code::Home,
        0xe052 => Code::Insert,
        0xe051 => Code::PageDown,
        0xe049 => Code::PageUp,
        0xe050 => Code::ArrowDown,
        0xe04b => Code::ArrowLeft,
        0xe04d => Code::ArrowRight,
        0xe048 => Code::ArrowUp,
        0xe045 => Code::NumLock,
        0x0052 => Code::Numpad0,
        0x004f => Code::Numpad1,
        0x0050 => Code::Numpad2,
        0x0051 => Code::Numpad3,
        0x004b => Code::Numpad4,
        0x004c => Code::Numpad5,
        0x004d => Code::Numpad6,
        0x0047 => Code::Numpad7,
        0x0048 => Code::Numpad8,
        0x0049 => Code::Numpad9,
        0x004e => Code::NumpadAdd,
        0x007e => Code::NumpadComma,
        0x0053 => Code::NumpadDecimal,
        0xe035 => Code::NumpadDivide,
        0xe01c => Code::NumpadEnter,
        0x0059 => Code::NumpadEqual,
        0x0037 => Code::NumpadMultiply,
        0x004a => Code::NumpadSubtract,
        0x0001 => Code::Escape,
        0x003b => Code::F1,
        0x003c => Code::F2,
        0x003d => Code::F3,
        0x003e => Code::F4,
        0x003f => Code::F5,
        0x0040 => Code::F6,
        0x0041 => Code::F7,
        0x0042 => Code::F8,
        0x0043 => Code::F9,
        0x0044 => Code::F10,
        0x0057 => Code::F11,
        0x0058 => Code::F12,
        0x0064 => Code::F13,
        0x0065 => Code::F14,
        0x0066 => Code::F15,
        0x0067 => Code::F16,
        0x0068 => Code::F17,
        0x0069 => Code::F18,
        0x006a => Code::F19,
        0x006b => Code::F20,
        0x006c => Code::F21,
        0x006d => Code::F22,
        0x006e => Code::F23,
        0x0076 => Code::F24,
        0xe037 => Code::PrintScreen,
        0x0054 => Code::PrintScreen, // Alt + PrintScreen
        0x0046 => Code::ScrollLock,
        0x0045 => Code::Pause,
        0xe046 => Code::Pause, // Ctrl + Pause
        0xe06a => Code::BrowserBack,
        0xe066 => Code::BrowserFavorites,
        0xe069 => Code::BrowserForward,
        0xe032 => Code::BrowserHome,
        0xe067 => Code::BrowserRefresh,
        0xe065 => Code::BrowserSearch,
        0xe068 => Code::BrowserStop,
        0xe06b => Code::LaunchApp1,
        0xe021 => Code::LaunchApp2,
        0xe06c => Code::LaunchMail,
        0xe022 => Code::MediaPlayPause,
        0xe06d => Code::MediaSelect,
        0xe024 => Code::MediaStop,
        0xe019 => Code::MediaTrackNext,
        0xe010 => Code::MediaTrackPrevious,
        0xe05e => Code::Power,
        0xe02e => Code::AudioVolumeDown,
        0xe020 => Code::AudioVolumeMute,
        0xe030 => Code::AudioVolumeUp,
        _ => return None,
    })
}
